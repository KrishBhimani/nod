import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { rm } from 'node:fs/promises';
import { join } from 'node:path';
import { setTimeout as delay } from 'node:timers/promises';
import test from 'node:test';
import pg from 'pg';
import type { RuntimeContext } from '../src/ports/agent.ts';
import type { ThreadDependencies } from '../src/server/thread.ts';
import { createSpeech } from '../src/server/speech.ts';

const audioFixture = new Uint8Array([
  73, 68, 51, 4, 0, 0, 0, 0, 0, 0, 102, 105, 120, 116, 117, 114, 101,
]);

test(
  'speech route and turn audio share generation; stopped or reset turns cannot publish',
  { skip: !process.env.TEST_DATABASE_URL, timeout: 30_000 },
  async (t) => {
    const suffix = randomUUID().replaceAll('-', '').slice(0, 16);
    const schema = `test_speech_${suffix}`;
    const bossSchema = `test_speech_boss_${suffix}`;
    const admin = new pg.Pool({ connectionString: process.env.TEST_DATABASE_URL });
    await admin.query(`CREATE SCHEMA ${schema}`);
    const url = new URL(process.env.TEST_DATABASE_URL!);
    url.searchParams.set('options', `-c search_path=${schema}`);
    process.env.DATABASE_URL = url.href;
    process.env.PGBOSS_SCHEMA = bossSchema;
    const db = await import('../src/server/db.ts');
    const thread = await import('../src/server/thread.ts');
    const { createPersonalService } = await import('../src/server/personal.ts');
    const { createApp } = await import('../src/server/app.ts');
    const { ownerId, dataRoot, port } = await import('../src/server/config.ts');

    let requests = 0;
    let release = () => {};
    let gate: Promise<void> | undefined;
    let waiting = false;
    let finished = false;
    let captured: RuntimeContext | undefined;
    const speech = createSpeech({
      id: 'fixture-speech',
      configured: true,
      transcribe: async () => 'fixture transcription',
      synthesize: async () => {
        requests++;
        if (gate) {
          waiting = true;
          await gate;
        }
        return { bytes: Buffer.from(audioFixture), mimeType: 'audio/mpeg', fileName: 'reply.mp3' };
      },
    });
    const app = await createApp({ speech });
    const personal = createPersonalService({
      pool: db.pool,
      ownerId,
      scheduler: thread.boss,
      enqueueTurn: thread.enqueueTurn,
      refresh() {},
    });
    const dependencies: ThreadDependencies = {
      speech,
      runTurn: async (context) => {
        captured = context;
        try {
          await context.createAudio!('Spoken fixture.');
          return { status: 'succeeded' };
        } finally {
          finished = true;
        }
      },
      requestCredential: async () => {
        throw new Error('Unused fixture');
      },
      integration: async () => ({}),
      manage: async () => ({}),
    };
    async function waitFor(predicate: () => Promise<boolean>) {
      for (let attempt = 0; attempt < 400; attempt++) {
        if (await predicate()) return;
        await delay(10);
      }
      assert.fail('Speech fixture did not reach its expected state.');
    }
    try {
      await db.initializeDatabase();
      await thread.initializeThreads();
      await personal.initialize({ workers: false });
      const response = await app.inject({
        method: 'POST',
        url: '/api/speech/speak',
        headers: { host: `localhost:${port}`, origin: `http://localhost:${port}` },
        payload: { text: 'Manual route fixture.' },
      });
      assert.equal(response.statusCode, 200);
      assert.equal(response.json().mimeType, 'audio/mpeg');
      assert.equal(response.json().name, 'reply.mp3');
      await thread.startThreadWorkers(dependencies);
      const { turnId: success } = await thread.submitUserMessage('Generate audio fixture');
      await waitFor(
        async () =>
          (await db.pool.query('SELECT status FROM turns WHERE id=$1', [success])).rows[0]
            .status === 'succeeded',
      );
      const messages = await db.pool.query(
        "SELECT text,attachments,thread_id FROM messages WHERE turn_id=$1 AND role='assistant'",
        [success],
      );
      assert.equal(messages.rowCount, 1);
      assert.equal(messages.rows[0].text, 'Audio generated by AI.');
      assert.equal(messages.rows[0].attachments[0].mimeType, 'audio/mpeg');
      assert.equal(
        (
          await db.pool.query('SELECT owner_id FROM artifacts WHERE thread_id=$1', [
            messages.rows[0].thread_id,
          ])
        ).rows[0].owner_id,
        ownerId,
      );
      assert.equal(requests, 2);

      for (const mode of ['stopped', 'reset']) {
        waiting = false;
        finished = false;
        gate = new Promise<void>((resolve) => {
          release = resolve;
        });
        const { turnId: id, threadId } = await thread.submitUserMessage(`Audio ${mode} fixture`);
        const artifactsBefore = (
          await db.pool.query('SELECT id FROM artifacts WHERE thread_id=$1', [threadId])
        ).rowCount;
        await waitFor(async () => waiting);
        if (mode === 'stopped') await thread.stopThread();
        else await thread.resetThread();
        release();
        await waitFor(async () => finished);
        gate = undefined;
        assert.equal(
          (await db.pool.query('SELECT status FROM turns WHERE id=$1', [id])).rows[0].status,
          'cancelled',
        );
        assert.equal(
          (await db.pool.query('SELECT id FROM artifacts WHERE thread_id=$1', [threadId])).rowCount,
          artifactsBefore,
        );
        assert.equal(
          (
            await db.pool.query("SELECT text FROM messages WHERE turn_id=$1 AND role='assistant'", [
              id,
            ])
          ).rowCount,
          0,
        );
        const before: number = requests;
        await assert.rejects(captured!.createAudio!('Must not contact the provider.'));
        assert.equal(requests, before);
      }
    } finally {
      release();
      await thread.stopThreadWorkers();
      await app.close();
      const files = (await db.pool.query('SELECT storage_path FROM artifacts')).rows.map((row) =>
        String(row.storage_path),
      );
      const ids = (await db.pool.query('SELECT id FROM threads')).rows.map((row) => String(row.id));
      await db.pool.end();
      for (const path of files) await rm(path, { force: true });
      for (const id of ids)
        await rm(join(dataRoot, 'workspaces', id), { recursive: true, force: true });
      await admin.query(`DROP SCHEMA IF EXISTS ${bossSchema} CASCADE`);
      await admin.query(`DROP SCHEMA ${schema} CASCADE`);
      await admin.end();
    }
  },
);
